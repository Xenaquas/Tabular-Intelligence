-- Verification script for Oracle 100 records fixture
-- Run connected as TABULA_DEMO_OWNER or TABULA_DEMO_RO inside FREEPDB1

SELECT 'TOTAL_USERS' AS METRIC, COUNT(*) AS VALUE FROM USERS
UNION ALL
SELECT 'TOTAL_CLAIMS', COUNT(*) FROM CLAIMS
UNION ALL
SELECT 'TOTAL_CLAIM_AMOUNT', SUM(CLAIM_AMOUNT) FROM CLAIMS
UNION ALL
SELECT 'RAHUL_CANDIDATES', COUNT(*) FROM USERS WHERE LOWER(FULL_NAME) LIKE '%rahul%'
UNION ALL
SELECT 'USER_1002_CLAIMS', COUNT(*) FROM CLAIMS WHERE USER_ID = 1002
UNION ALL
SELECT 'USERS_WITH_ZERO_CLAIMS', COUNT(*) FROM USERS u WHERE NOT EXISTS (SELECT 1 FROM CLAIMS c WHERE c.USER_ID = u.USER_ID);
